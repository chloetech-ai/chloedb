#!/bin/sh
# Write the Homebrew formula of a chloedb-server release to stdout:
#
#   packaging/homebrew/formula.sh VERSION DIR > chloedb.rb
#
# DIR holds the release's checksum files, chloedb-server-<platform>.tar.gz.sha256
# for macos-arm64, macos-x86_64, linux-x86_64 and linux-aarch64, as
# server-release.yml makes them. The formula installs the prebuilt server
# from the release's archives (no Rust, no build), on macOS and on Linux
# (Homebrew on Linux, glibc 2.35 or later).
#
# server-release.yml runs this for a tag and attaches chloedb.rb to the
# release; with the repository variable CHLOEDB_HOMEBREW_TAP set (a tap
# repository, chloetech-ai/homebrew-tap) and the secret HOMEBREW_TAP_TOKEN
# (a token that can push to it), it also commits the formula there, so that
#
#   brew install chloetech-ai/tap/chloedb
#
# installs the new version. CHLOEDB_RELEASES_URL replaces the download
# address (for testing, a file:// URL of a folder laid out as the releases
# are: <url>/chloedb-server-v<version>/chloedb-server-<platform>.tar.gz).
set -eu

[ $# -eq 2 ] || { echo "usage: $0 VERSION DIR" >&2; exit 2; }
version=${1#v}
dir=$2
base="${CHLOEDB_RELEASES_URL:-https://github.com/chloetech-ai/chloedb/releases/download}/chloedb-server-v$version"

sum() {
  f="$dir/chloedb-server-$1.tar.gz.sha256"
  [ -f "$f" ] || { echo "$0: no $f" >&2; exit 1; }
  s=$(cut -d' ' -f1 < "$f")
  case "$s" in
    *[!0-9a-f]* | "") echo "$0: $f holds no SHA-256" >&2; exit 1 ;;
  esac
  [ ${#s} -eq 64 ] || { echo "$0: $f holds no SHA-256" >&2; exit 1; }
  printf '%s' "$s"
}

macos_arm64=$(sum macos-arm64)
macos_x86_64=$(sum macos-x86_64)
linux_x86_64=$(sum linux-x86_64)
linux_aarch64=$(sum linux-aarch64)

cat <<EOF
# Generated by packaging/homebrew/formula.sh in chloetech-ai/chloedb for
# chloedb-server $version: edit that script, not this file.
class Chloedb < Formula
  desc "Embedded search database with SQL: full text, vectors and graphs in one file"
  homepage "https://chloetech-ai.github.io/chloedb/"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/chloedb-server-macos-arm64.tar.gz"
      sha256 "$macos_arm64"
    end
    on_intel do
      url "$base/chloedb-server-macos-x86_64.tar.gz"
      sha256 "$macos_x86_64"
    end
  end

  on_linux do
    on_arm do
      url "$base/chloedb-server-linux-aarch64.tar.gz"
      sha256 "$linux_aarch64"
    end
    on_intel do
      url "$base/chloedb-server-linux-x86_64.tar.gz"
      sha256 "$linux_x86_64"
    end
  end

  def install
    bin.install "chloedb-server"
  end

  def caveats
    <<~EOS
      Try it: a demo catalogue with the query console at http://127.0.0.1:7700
        chloedb-server --demo 20000 --db demo.chloedb
      The five-minute guide: https://github.com/chloetech-ai/chloedb/blob/main/docs/quickstart.md
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/chloedb-server --version")
    port = free_port
    pid = spawn "#{bin}/chloedb-server", "--db", "#{testpath}/t.chloedb", "--listen", "127.0.0.1:#{port}", "--grpc", "off"
    api = "http://127.0.0.1:#{port}"
    (testpath/"create.json").write '{"sql": "CREATE TABLE notes (id KEYWORD PRIMARY KEY, body TEXT)"}'
    (testpath/"write.json").write '{"ops": [{"op": "upsert", "table": "notes", "doc": {"id": "a", "body": "rivers and mountains"}}]}'
    (testpath/"query.json").write '{"sql": "SELECT id FROM notes WHERE MATCH(body, \'rivers\')"}'
    begin
      30.times do
        break if quiet_system "curl", "-sf", "#{api}/livez"

        sleep 1
      end
      json = ["-H", "content-type: application/json"]
      system "curl", "-sf", "#{api}/v1/sql", *json, "-d", "@#{testpath}/create.json"
      system "curl", "-sf", "#{api}/v1/write", *json, "-d", "@#{testpath}/write.json"
      assert_match '"a"', shell_output("curl -sf #{api}/v1/query -H 'content-type: application/json' -d @#{testpath}/query.json")
    ensure
      Process.kill("TERM", pid)
      Process.wait(pid)
    end
  end
end
EOF
